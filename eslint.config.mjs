/**
 * Turns every `warn` of a preset into `error`. The security plugin ships its recommended set as
 * `warn`, which would let a finding through unnoticed in an editor and fail CI only through
 * --max-warnings. One severity keeps the gate easy to read.
 */
function warnAsError(config) {
  const escalate = (value) => {
    if (value === 'warn') return 'error';
    if (Array.isArray(value) && value[0] === 'warn') return ['error', ...value.slice(1)];
    return value;
  };
  const entries = Object.entries(config.rules).map(([name, value]) => [name, escalate(value)]);
  return { ...config, rules: Object.fromEntries(entries) };
}

