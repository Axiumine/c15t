// ESLint is a zero-findings gate next to Biome: `yarn lint:eslint` runs with --max-warnings 0, so a
// rule is either an error or off (there is no `warn` anywhere in this file).
//
// Division of labour with Biome (`yarn lint`, biome.json):
//   - Biome formats, sorts imports and runs the fast syntactic lint, including the React rules
//     (useHookAtTopLevel and useExhaustiveDependencies, switched on by its "react" domain). That is
//     why eslint-plugin-react-hooks is not installed: it would only repeat them.
//   - ESLint adds what Biome cannot do: type-aware rules (typescript-eslint strictTypeChecked), the
//     SonarJS bug and code-smell rules, eslint-plugin-security and eslint-plugin-no-unsanitized.
//   - Where both tools have a rule, Biome keeps it and the ESLint twin is turned off below
//     ("Biome owns"), so a finding is reported once and the two cannot disagree.
//
// Type-aware rules need the declaration files of the referenced workspaces, so run `yarn typecheck`
// (tsc -b) before `yarn lint:eslint` in a fresh checkout and in CI.

