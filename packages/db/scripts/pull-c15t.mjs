// `yarn db:pull-c15t`: introspect the `c15t` schema with drizzle-kit and write
// src/c15t.generated.ts. Rerun after every c15t upgrade (README D4).
import { spawnSync } from 'node:child_process';
import { existsSync, mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const pkg = join(dirname(fileURLToPath(import.meta.url)), '..');
const repoRoot = join(pkg, '..', '..');
const out = join(pkg, '.tsbuild', 'c15t-pull');
const target = join(pkg, 'src', 'c15t.generated.ts');

rmSync(out, { recursive: true, force: true });
mkdirSync(out, { recursive: true });

// Run from the repository root: drizzle-kit looks for its dotenv-style file in the working
// directory, and Yarn's injected variables work from anywhere.
const drizzleKit = join(dirname(createRequire(import.meta.url).resolve('drizzle-kit')), 'bin.cjs');
const result = spawnSync(
  process.execPath,
  [drizzleKit, 'pull', '--config', 'packages/db/drizzle.c15t.config.ts'],
  { cwd: repoRoot, stdio: 'inherit' },
);
if (result.status !== 0) process.exit(result.status ?? 1);

const pulled = join(out, 'schema.ts');
if (!existsSync(pulled)) {
  console.error('drizzle-kit did not write schema.ts. Does the c15t schema have tables yet?');
  process.exit(1);
}

// drizzle-kit imports helpers the schema may not use, and tsc runs with noUnusedLocals.
function dropUnusedImports(source) {
  const lines = source.split('\n');
  const importLine = /^import \{ (.+) \} from (".+")$/;
  const body = lines.filter((line) => !importLine.test(line)).join('\n');
  return lines
    .map((line) => {
      const match = importLine.exec(line);
      if (match === null) return line;
      const used = match[1].split(', ').filter((name) => new RegExp(`\\b${name}\\b`).test(body));
      return used.length === 0 ? null : `import { ${used.join(', ')} } from ${match[2]}`;
    })
    .filter((line) => line !== null)
    .join('\n');
}

const header = [
  '// GENERATED by `yarn db:pull-c15t` from the live `c15t` schema. Do not edit.',
  '// Read-only use: dashboard-api never writes to c15t.* (README D4).',
  '',
].join('\n');
writeFileSync(target, header + dropUnusedImports(readFileSync(pulled, 'utf8')));
console.warn(`wrote ${target}`);
